/**
 * Build both halves of the plugin.
 *
 * The host half is a plain ESM module for Node. The browser half has to be a
 * CommonJS bundle wrapped in the page's module-loader registration
 * (`window.__ModuleLoader__.load({ id, factory })`), because that is the shape
 * the Harness client loader executes. `react` stays external and is resolved
 * from the factory's own `require`.
 */
import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url)).replace(/[\\/]scripts$/, '')
const out = join(root, 'lib')
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))

/** Host half: one bundled ESM file, node builtins only. */
await build({
  entryPoints: [join(root, 'src/host.ts')],
  outfile: join(out, 'index.js'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  sourcemap: false,
  logLevel: 'warning',
})

/** Browser half: CJS bundle, `react` supplied by the loader's factory. */
const clientBundle = await build({
  entryPoints: [join(root, 'src/client.ts')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  external: ['react', 'react-dom'],
  logLevel: 'warning',
})

const body = clientBundle.outputFiles[0]?.text ?? ''
const wrapped = `/* ${pkg.name}@${pkg.version} — generated by scripts/build.mjs; do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
    (function (module, exports, require) {
${body}
    })(module, exports, require);
    return module.exports;
  },
});
`
await mkdir(out, { recursive: true })
await writeFile(join(out, 'client.js'), wrapped, 'utf8')

console.log(`built lib/index.js (${(await readFile(join(out, 'index.js'))).length} B) and lib/client.js (${wrapped.length} B)`)
